def _write_layout_a(zf: zipfile.ZipFile, doc_id: str, pages: list[str]) -> None:
    """A) doc39/texts/page_001.txt + doc39/images/page_001.jpg"""
    for i, text in enumerate(pages, 1):
        zf.writestr(f"{doc_id}/texts/page_{i:03d}.txt", text)
        zf.writestr(f"{doc_id}/images/page_{i:03d}.jpg", _TINY_JPEG)


def _write_layout_b(zf: zipfile.ZipFile, doc_id: str, pages: list[str]) -> None:
    """B) page_001.txt + page_001.jpg (평면)"""
    for i, text in enumerate(pages, 1):
        zf.writestr(f"page_{i:03d}.txt", text)
        zf.writestr(f"page_{i:03d}.jpg", _TINY_JPEG)


def _write_layout_c(zf: zipfile.ZipFile, doc_id: str, pages: list[str]) -> None:
    """C) ocr.json 통합 + 이미지"""
    payload = {"doc_id": doc_id,
               "pages": [{"page": i, "text": t} for i, t in enumerate(pages, 1)]}
    zf.writestr("ocr.json", json.dumps(payload, ensure_ascii=False, indent=1))
    for i in range(1, len(pages) + 1):
        zf.writestr(f"images/{i:04d}.jpg", _TINY_JPEG)


_WRITERS = {"A": _write_layout_a, "B": _write_layout_b, "C": _write_layout_c}


def build(target_dir: Path = MOCK_CORPUS_DIR) -> list[Path]:
    target_dir.mkdir(parents=True, exist_ok=True)
    written: list[Path] = []
    for doc_id, spec in DOCS.items():
        path = target_dir / f"{doc_id}.zip"
        with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
            _WRITERS[spec["layout"]](zf, doc_id, spec["pages"])
        written.append(path)
    return written


def main() -> int:
    paths = build()
    print(f"mock 코퍼스 {len(paths)}건 생성 → {MOCK_CORPUS_DIR}")
    for p in paths:
        layout = DOCS[p.stem]["layout"]
        print(f"  · {p.name}  (레이아웃 {layout})")
    print("\n⚠️ 실제 제공 자료가 아닙니다. 실물 zip을 받으면 data/corpus/ 에 넣으십시오.")
    return 0


