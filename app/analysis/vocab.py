"""연금 도메인 용어 사전 — 동의어 확장과 핵심어 판정.

슬롯-근거 매칭, 답변-슬롯 매칭, 질의 분석이 모두 이 사전을 공유한다.
용어를 늘리려면 여기 한 곳만 고치면 된다.

⚠️ 동의어로 묶어도 되는 것과 안 되는 것을 구분할 것.
   "연금수령연차"와 "연금실제수령연차"는 **절대 동의어가 아니다**
   (전자는 수령한도, 후자는 퇴직소득세 감면율을 결정 — doc40이 직접 경고하는 함정).
   아래 그룹에서 두 용어는 분리돼 있으며, 이 분리는 유지해야 한다.
"""

from __future__ import annotations

from app.retrieval.tokenize import content_terms

# ── 동의어 그룹 ────────────────────────────────────────────────
# 같은 그룹 안의 용어는 매칭 시 상호 치환 가능하다고 본다.
SYNONYM_GROUPS: list[set[str]] = [
    {"세액공제", "세액공제액", "세액공제한도", "공제한도", "세액공제율"},
    {"연금저축", "연금저축계좌", "연금저축펀드", "연금저축보험", "연저축"},
    {"irp", "개인형퇴직연금", "개인형", "아이알피"},
    {"퇴직연금", "퇴직연금제도", "퇴직급여제도"},
    {"납입한도", "납입limit", "불입한도", "납입가능금액"},
    {"연금수령한도", "수령한도", "인출한도"},
    {"연금수령연차", "수령연차"},                      # ≠ 연금실제수령연차
    {"연금실제수령연차", "실제수령연차"},              # ≠ 연금수령연차
    {"퇴직소득세", "퇴직소득세액", "이연퇴직소득세"},
    {"연금소득세", "연금소득세율"},
    {"기타소득세", "기타소득세율"},
    {"분리과세", "분리과세선택"},
    {"종합과세", "종합소득세", "종합소득과세"},
    {"원천징수", "원천징수세율", "떼는세금", "떼는돈"},
    {"중도인출", "중도해지", "인출"},
    {"총보수", "보수율", "수수료", "총보수비용"},
    {"위험등급", "투자위험등급"},
    {"판매클래스", "클래스", "종류형"},
    {"가입자격", "가입요건", "가입가능"},
    {"근속연수", "재직연수", "근무기간"},
    {"퇴직급여", "퇴직금", "명예퇴직금", "명퇴금"},
    {"국민연금", "노령연금", "공적연금"},
    {"출산크레딧", "출산크레디트"},
    {"과세이연", "세금이연"},
    {"연금개시", "수령개시", "연금수령개시"},
    {"지방소득세", "주민세"},
    {"세율", "적용세율"},
    {"한도", "상한", "최대"},
]

# 용어 → 그룹 인덱스
_TERM_TO_GROUP: dict[str, int] = {}
for _i, _g in enumerate(SYNONYM_GROUPS):
    for _t in _g:
        _TERM_TO_GROUP[_t] = _i

# 도메인 핵심어 — 이 중 하나라도 겹쳐야 "주제가 같다"고 본다.
DOMAIN_TERMS: set[str] = set(_TERM_TO_GROUP) | {
    "연금", "수령", "납입", "과세", "세금", "공제", "인출", "이전", "해지",
    "계좌", "상품", "펀드", "수익률", "적립", "지급", "개시", "가입",
    "확정급여", "확정기여", "db", "dc", "부득이한사유", "담보대출",
    "연금소득", "사적연금", "환매", "가입자교육", "제도전환",
}

# 매칭에서 제외할 지나치게 일반적인 말 (있어도 주제 동일성의 근거가 못 된다)
GENERIC_TERMS: set[str] = {
    "금액", "기준", "내용", "사항", "경우", "관련", "확인", "가능", "필요",
    "적용", "해당", "이상", "이하", "초과", "미만", "설명", "안내", "표시",
    "제공", "자료", "문서", "정보", "방법", "산정", "계산",
}


def expand(terms: set[str]) -> set[str]:
    """동의어 그룹으로 용어 집합을 확장."""
    out = set(terms)
    for t in terms:
        gi = _TERM_TO_GROUP.get(t)
        if gi is not None:
            out |= SYNONYM_GROUPS[gi]
    return out


def key_terms(text: str) -> set[str]:
    """매칭에 쓸 핵심어 집합.

    일반어(GENERIC_TERMS)와 1글자 토큰을 제거한 뒤 동의어로 확장한다.
    """
    raw = {t for t in content_terms(text) if t not in GENERIC_TERMS and len(t) >= 2}
    return expand(raw)


def domain_hits(terms: set[str]) -> set[str]:
    """도메인 핵심어에 해당하는 것만 추린다."""
    return {t for t in terms if t in DOMAIN_TERMS}
