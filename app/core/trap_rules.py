"""
함정 문항 감지 규칙 (Trap Detection Rules)
==========================================
미래에셋 제공문서 전수 조사로 도출한 '틀리기 쉬운 지점' 카탈로그.

각 규칙은 다음을 갖는다:
  · trigger  : 질의에서 이 함정이 걸리는 조건 (키워드/조합)
  · fact     : 문서에 근거한 정확한 사실
  · source   : 근거 문서 ID
  · correction: 잘못된 전제를 바로잡는 응답 문구
  · ask_back : 확인이 필요한 경우 되물을 항목

사용처
------
1) 질의 분석 직후 — 해당 함정이 걸리는지 판정
2) 답변 생성 전 — correction 문구를 Supervisor 컨텍스트에 주입
3) think_trace — "이 질의는 ○○ 혼동 위험이 있어 확인했다"를 기록

⚠️ 이 카탈로그는 '문서에 명시된 것'만 담는다. 일반 세법 지식으로 추론한 항목은
   is_document_backed=False로 표시하고, 답변 시 출처가 제공자료가 아님을 밝힌다.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Callable

# source 필드에서 실제 문서 ID만 추려내기 위한 패턴.
# "doc39 · doc40 · R2_KR516702010M" → {doc39, doc40, R2_KR516702010M}
# "각 투자설명서" 처럼 문서를 특정하지 못하는 서술은 걸러진다.
_DOC_ID = re.compile(r'\b(doc\d+|R2_[A-Za-z0-9]+)\b')


@dataclass
class TrapRule:
    id: str
    title: str
    severity: str                    # "critical" | "high" | "medium"
    trigger_keywords: list[str]
    trigger_all: list[str] = field(default_factory=list)  # 이 단어들이 모두 있을 때만
    fact: str = ""
    source: str = ""
    correction: str = ""
    ask_back: str = ""
    is_document_backed: bool = True

    def source_doc_ids(self) -> set[str]:
        """source 문자열에서 근거 문서 ID를 뽑는다.

        ━━ 이게 왜 중요한가 ━━
        함정 감지(L2)는 정밀 검색(L3)보다 **먼저** 돈다. 즉 시스템은
        "이 질의는 명예퇴직 함정에 걸린다 → doc55를 봐야 한다"는 것을
        검색을 시작하기도 전에 알고 있다. 그런데 예전에는 이 정보가
        검색으로 전달되는 경로가 없어서, 알면서도 엉뚱한 문서를 근거로
        답했다(Q-001 실패). 이 메서드가 그 경로의 출발점이다.
        """
        return set(_DOC_ID.findall(self.source or ""))


