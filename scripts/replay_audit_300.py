def _includes(answer: str, term: str) -> bool:
    """tests/eval_set.py의 _includes()와 같은 기준.

    금액 표기가 흔들려도("1200만원" vs "1,200만원") 같은 값이면 통과시킨다.
    금액이 아닌 항목은 완전 일치로만 통과한다 — 느슨해지는 게 아니다.
    """
    if term in answer:
        return True
    try:
        from app.analysis.units import parse_amount_expressions
    except ImportError:
        return False    # 저장소 루트가 아닌 곳에서 실행됐다면 그냥 문자열 일치만
    want = [v for _s, _e, v in parse_amount_expressions(term)]
    if not want:
        return False
    have = {v for _s, _e, v in parse_amount_expressions(answer)}
    return all(w in have for w in want)


def ask(base_url: str, qid: str, question: str, timeout: float) -> dict:
    url = f"{base_url}/answer?" + urllib.parse.urlencode(
        {"question_id": qid, "question": question})
    t0 = time.time()
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:
            body = json.loads(r.read().decode("utf-8"))
        body["_elapsed"] = round(time.time() - t0, 2)
        body["_http_error"] = None
    except Exception as e:      # noqa: BLE001 — 어떤 실패든 결과에 남긴다
        body = {"question_id": qid, "question": question, "answer": "",
                "retrieved_context": "", "think_trace": "",
                "_elapsed": round(time.time() - t0, 2), "_http_error": str(e)}
    return body


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--base-url", default="http://localhost")
    ap.add_argument("--concurrency", type=int, default=6)
    ap.add_argument("--only", default="", help="카테고리 접두어(쉼표구분), 예: A,L")
    ap.add_argument("--timeout", type=float, default=60.0)
    ap.add_argument("--out", default="")
    args = ap.parse_args()

    cases = [c for c in CASES if c[0] not in DESCRIPTIVE]
    if args.only:
        prefixes = tuple(p.strip() for p in args.only.split(","))
        cases = [c for c in cases if c[0].startswith(prefixes)]

    skipped_descriptive = [c[0] for c in CASES if c[0] in DESCRIPTIVE]
    print(f"총 {len(cases)}건 실행 (동시 {args.concurrency}) → {args.base_url}")
    if not args.only and skipped_descriptive:
        print(f"  (설명형 문항 {skipped_descriptive}는 원본 입력 문자열이 아니라 "
              f"자동 재현에서 뺐습니다)")

    results: list[dict] = []
    with ThreadPoolExecutor(max_workers=args.concurrency) as ex:
        futs = {ex.submit(ask, args.base_url, cid, q, args.timeout): (cid, q, exp, ov, oc)
                for cid, q, exp, ov, oc in cases}
        done = 0
        for fut in as_completed(futs):
            cid, q, exp, ov, oc = futs[fut]
            body = fut.result()
            answer = body.get("answer", "")
            hit = _includes(answer, exp) if exp else None
            results.append({
                "id": cid, "question": q, "expected": exp,
                "old_verdict": ov, "old_code": oc,
                "auto_hit": hit, "elapsed": body.get("_elapsed"),
                "http_error": body.get("_http_error"),
                "answer": answer,
                "retrieved_context": body.get("retrieved_context", ""),
                "think_trace": body.get("think_trace", ""),
            })
            done += 1
            mark = "?" if hit is None else ("O" if hit else "X")
            print(f"  [{done:>3}/{len(cases)}] {mark} {cid}  ({body.get('_elapsed')}s)")

    by_cat: dict[str, dict[str, int]] = defaultdict(
        lambda: {"n": 0, "hit": 0, "unknown": 0, "err": 0})
    for r in results:
        cat = r["id"][0]
        by_cat[cat]["n"] += 1
        if r["http_error"]:
            by_cat[cat]["err"] += 1
        elif r["auto_hit"] is None:
            by_cat[cat]["unknown"] += 1
        elif r["auto_hit"]:
            by_cat[cat]["hit"] += 1

    print("\n" + "=" * 64)
    print(f"{'카테고리':<20}{'건수':<6}{'자동일치':<8}{'수동필요':<8}{'오류':<6}")
    print("-" * 64)
    for cat in sorted(by_cat):
        s = by_cat[cat]
        name = CAT_NAMES.get(cat, cat)
        print(f"{name:<20}{s['n']:<6}{s['hit']:<8}{s['unknown']:<8}{s['err']:<6}")

    total = len(results)
    total_hit = sum(1 for r in results if r["auto_hit"])
    total_unknown = sum(1 for r in results if r["auto_hit"] is None)
    total_err = sum(1 for r in results if r["http_error"])
    print("-" * 64)
    print(f"{'합계':<20}{total:<6}{total_hit:<8}{total_unknown:<8}{total_err:<6}")
    print("=" * 64)
    print("⚠️ '자동일치'는 기대 키워드 포함 여부만 본 1차 신호일 뿐이다.")
    print("   PASS/PARTIAL/FAIL 최종 판정은 --out 파일을 열어 answer 원문을")
    print("   직접 읽고 사람이 내려야 한다 (원본 감사도 그렇게 했다).")
    if total_err:
        print(f"\n⚠️ HTTP 오류 {total_err}건 — 서버가 안 떠 있거나 타임아웃일 수 있다.")

    out_path = args.out or f"replay_result_{int(time.time())}.json"
    Path(out_path).write_text(
        json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n전체 응답(질문+답변+근거+think_trace) 저장: {out_path}")


if __name__ == "__main__":
    main()
