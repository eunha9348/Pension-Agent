"""A9 · 연금 외 수령 시 재원별 과세 구분 (2026-09-01 추가).

━━ 왜 필요했나 ━━
실물 질의 "퇴직금을 IRP로 이체한 후 일부는 연금으로 수령하고 나머지는
중도에 일시금으로 인출하면 세금이 각각 어떻게 계산되나요?"에 대해
에이전트가 **"중도 일시금 인출 시 전액 기타소득세 16.5%"**라고 답했다.

IRP 안의 돈은 성격이 나뉜다:
  ① 퇴직급여를 이체한 원금 (이연퇴직소득) → 퇴직소득 과세기준
  ② 세액공제받은 납입액 + 운용수익        → 기타소득세 16.5%
  ③ 세액공제받지 않은 납입액              → 과세 대상 아님

이 구분이 빠지면 세금 안내로서 틀린다. 기존 26종 중 이를 다루는 규칙이
없었다 — A7은 "IRP는 부분인출 불가"만, C6은 연금수령 시 감면율만 다룬다.

━━ 문서 근거 ━━
투자설명서 [연금저축계좌 과세 주요 사항] 표가 이렇게 적고 있다:

    연금 외 수령시 과세   기타소득 분리과세 16.5% (지방소득세 포함)
                          단, 이연퇴직소득은 퇴직소득 과세기준 적용

일반 세법 지식으로 추론한 것이 아니라 제공 자료에 실재하는 단서다.

━━ 트리거 설계의 근거 (실측) ━━
'인출 행위'만으로 확정하면 세금을 묻지 않는 질의까지 끌어온다.
298건 실측에서 인출 주제어만 쓰면 13건 발화 중 5건이 오탐이었다
(D03 부분인출 가능?, D05·R10 인출 사유, D19 DC 인출 가능?, J07 이체 시 해지).
그래서 '과세' 맥락어를 함께 요구한다. 맥락어에서 '얼마'를 뺀 것도
실측 때문이다 — "얼마까지 인출할 수 있나요"(L01·수령한도)가 걸렸다.
최종 발화율 16/298건, 전부 인출 과세 질의다.
"""

from __future__ import annotations

from app.core.trap_rules import TRAPS, detect_traps, verify_terms_for

A9 = next(r for r in TRAPS if r.id == "A9")


def _ids(q: str) -> list[str]:
    return [r.id for r in detect_traps(q)]


# ── 발화해야 하는 질의 ───────────────────────────────────────

def test_실물_보고_질의에서_발화한다():
    """★ 사고를 일으킨 바로 그 질의."""
    q = ("퇴직금을 IRP로 이체한 후 일부는 연금으로 수령하고 나머지는 "
         "중도에 일시금으로 인출하면 세금이 각각 어떻게 계산되나요?")
    assert "A9" in _ids(q)


def test_인출_과세_질의에서_발화한다():
    for q in ("IRP를 중도해지하면 세금이 어떻게 되나요?",
              "IRP로 받은 퇴직금을 중간에 일시금으로 찾으면 세금이 어떻게 되나요?",
              "퇴직금 재원과 세액공제 받은 납입금은 인출할 때 세율이 다른가요?",
              "연금저축을 해지하면 기타소득세 16.5%가 원금 전체에 붙나요?",
              "전액 세액공제를 받은 IRP 5000만원을 일시금으로 해지하면 "
              "실제 손에 쥐는 돈은 얼마인가요?"):
        assert "A9" in _ids(q), q


# ── 발화하면 안 되는 질의 (실측된 오탐 패턴) ─────────────────

def test_세금을_묻지_않는_인출_질의에는_발화하지_않는다():
    """★ 인출 주제어만으로 확정했을 때 실제로 잡혔던 5건."""
    for q in ("IRP는 부분 인출이 가능한가요?",
              "퇴직연금 중도인출이 가능한 법정 사유를 모두 알려주세요.",
              "회사가 도산했는데 DC형에서 인출할 수 있나요?",
              "연금계좌를 이체할 때 기존 계좌를 해지해야 하나요?",
              "퇴직연금 중도인출 사유좀"):
        assert "A9" not in _ids(q), q


def test_수령한도_질의에는_발화하지_않는다():
    """★ 맥락어에 '얼마'를 넣었을 때 잡혔던 L01."""
    q = "계좌에 1억원 있고 연금수령 1년차인데 얼마까지 인출할 수 있나요?"
    assert "A9" not in _ids(q)


def test_인출과_무관한_과세_질의에는_발화하지_않는다():
    for q in ("연금저축과 IRP를 합쳐서 연간 세액공제 한도는 얼마인가요?",
              "연간 연금수령액이 1500만원을 넘으면 세금이 어떻게 되나요?",
              "총급여 5천만원 근로자가 900만원 납입하면 환급액은 얼마인가요?"):
        assert "A9" not in _ids(q), q


def test_298건_발화율이_측정값과_같다():
    """★ 문턱을 건드리면 이 수치가 움직인다 — 움직이면 다시 실측할 것."""
    from scripts.replay_audit_300 import CASES, DESCRIPTIVE

    fired = [c for c, q, *_ in CASES
             if c not in DESCRIPTIVE and "A9" in _ids(q)]
    assert len(fired) == 16, f"발화율이 바뀌었다: {fired}"


